//! `cargo xtask bindings [--check]`: the `@zenith/contracts` TypeScript
//! package in bindings/ (#125).
//!
//! Builds every complete contract's wasm, runs `stellar contract bindings
//! typescript` on it, and writes the generated client to
//! `bindings/src/contracts/<contract>.ts`. `bindings/src/index.ts`
//! re-exports each one as a namespace (`params.Client`,
//! `multisig.Client`, ...), so types that several contracts define under
//! the same name (`InitializedEvent`, `DataKey`, `Errors`) never collide.
//! `bindings/src/events.ts` embeds events.json for typed event decoding.
//!
//! With `--check`, nothing is written: the command fails if any generated
//! file differs from what's committed, i.e. the ABI changed without a
//! bindings update. Needs the `stellar` CLI on PATH (CI pins its version).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::{Opts, Result, Workspace};

const OUT: &str = "bindings/src";

pub fn bindings(ws: &Workspace, opts: &Opts) -> Result<()> {
    let contracts = ws.contracts();
    ws.build_wasm(&contracts.iter().cloned().collect())?;

    let scratch = ws.target_dir.join("bindings-gen");
    let mut files: Vec<(PathBuf, String)> = Vec::new();
    let mut names = Vec::new();
    for name in &contracts {
        let short = short_name(ws, name);
        let out = scratch.join(&short);
        let wasm = ws.wasm_path(name)?;
        let status = Command::new("stellar")
            .args([
                "contract",
                "bindings",
                "typescript",
                "--overwrite",
                "--wasm",
            ])
            .arg(&wasm)
            .arg("--output-dir")
            .arg(&out)
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .map_err(|e| format!("failed to run `stellar` (is stellar-cli on PATH?): {e}"))?;
        if !status.success() {
            return Err(format!(
                "stellar contract bindings failed for {name} ({status})"
            ));
        }
        let generated = fs::read_to_string(out.join("src").join("index.ts"))
            .map_err(|e| format!("reading generated bindings for {name}: {e}"))?;
        files.push((
            ws.root
                .join(OUT)
                .join("contracts")
                .join(format!("{short}.ts")),
            format!(
                "// @generated by `cargo xtask bindings` from {name}'s contract spec.\n\
                 // Do not edit: regenerate instead. CI runs `cargo xtask bindings --check`.\n\n\
                 {generated}"
            ),
        ));
        names.push(short);
    }

    files.push((ws.root.join(OUT).join("index.ts"), index_ts(&names)));
    let events = fs::read_to_string(ws.root.join("events.json"))
        .map_err(|e| format!("reading events.json: {e}"))?;
    files.push((ws.root.join(OUT).join("events.ts"), events_ts(&events)));

    if opts.check {
        let stale: Vec<String> = files
            .iter()
            .filter(|(path, content)| fs::read_to_string(path).ok().as_deref() != Some(content))
            .map(|(path, _)| rel(ws, path))
            .collect();
        if !stale.is_empty() {
            return Err(format!(
                "generated bindings are out of date (run `cargo xtask bindings` and commit):\n  {}",
                stale.join("\n  ")
            ));
        }
        eprintln!(
            "xtask: bindings for {} contracts are up to date",
            names.len()
        );
    } else {
        let dir = ws.root.join(OUT).join("contracts");
        // Drop clients of contracts that no longer exist.
        if let Ok(entries) = fs::read_dir(&dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if !files.iter().any(|(p, _)| *p == path) {
                    fs::remove_file(&path).map_err(|e| e.to_string())?;
                }
            }
        }
        for (path, content) in &files {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).map_err(|e| e.to_string())?;
            }
            fs::write(path, content).map_err(|e| format!("writing {}: {e}", rel(ws, path)))?;
        }
        eprintln!("xtask: wrote bindings for {}", names.join(", "));
    }
    Ok(())
}

/// The crate's directory name: `zenith-grants-escrow` -> `grants_escrow`.
fn short_name(ws: &Workspace, name: &str) -> String {
    ws.packages[name]
        .dir
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or(name)
        .to_string()
}

fn rel(ws: &Workspace, path: &Path) -> String {
    path.strip_prefix(&ws.root)
        .unwrap_or(path)
        .display()
        .to_string()
}

fn index_ts(names: &[String]) -> String {
    let mut s = String::from(
        "// @generated by `cargo xtask bindings`. Do not edit.\n\
         //\n\
         // One namespace per contract, so same-named types in different\n\
         // contracts (InitializedEvent, DataKey, Errors, ...) don't collide:\n\
         //\n\
         //   import { streams, networks } from \"@zenith/contracts\";\n\
         //   const client = new streams.Client({ ...networks.testnet, contractId });\n\n",
    );
    for n in names {
        s.push_str(&format!("export * as {n} from \"./contracts/{n}.js\";\n"));
    }
    s.push_str("export * from \"./networks.js\";\nexport * from \"./events.js\";\n");
    s
}

fn events_ts(json: &str) -> String {
    format!(
        "// @generated by `cargo xtask bindings` from events.json. Do not edit.\n\n\
         /** The machine-readable event spec (events.json, schema v2). */\n\
         export const eventSpec = {} as const;\n\n\
         export type EventSpec = typeof eventSpec;\n\
         export type ContractName = keyof EventSpec[\"contracts\"];\n\
         export type EventName<C extends ContractName> =\n  \
         EventSpec[\"contracts\"][C][\"events\"][number][\"name\"];\n\n\
         export {{ decodeEvent, type DecodedEvent }} from \"./decode.js\";\n",
        json.trim_end()
    )
}
