#![no_std]

//! Shared admin/multisig/pause helpers for the Zenith contracts.
//!
//! Every admin-gated function in options_market, price_oracle and vault
//! has a `_via_multisig` twin. Both entrypoints now call the same
//! `x_inner(env, Auth, ...)`, which starts with
//! `require_admin_or_multisig` — so validation lives in one place and a
//! security fix to the auth check is made once, here.
//!
//! Deliberately defines no `#[contract]` and exports no contract spec
//! entries, so linking it can't change any consumer's public ABI.
//!
//! Also home to the storage-schema migration framework (`migrations`),
//! the upgrade-safety framework (`upgrade`: pinned multisig, wasm hash
//! allowlist, post-upgrade self-check) and the contract metadata macro
//! (`meta`) every contract uses — see docs/migrations.md and
//! docs/upgrades.md.
//!
//! Every helper returns `Result<_, E>` with the calling contract's own
//! error codes, so entrypoints propagate typed errors with `?` and never
//! trap untyped (docs/errors.md).

pub mod events;
pub mod migrations;
pub mod upgrade;

/// Embeds the calling contract's metadata (`name`, `binver`,
/// `source_repo`, `commit`) as `contractmeta!` entries. The values are
/// generated by common/build_meta.rs, which the crate must use as its
/// build script (`build = "../common/build_meta.rs"`).
#[macro_export]
macro_rules! contract_meta {
    () => {
        include!(concat!(env!("OUT_DIR"), "/contractmeta.rs"));
    };
}

