use soroban_sdk::{contracttype, vec, Address, Env, IntoVal, Symbol, Val};

/// Mirrors multisig's `ActionClass` (same `u32` encoding) without
/// exporting a spec entry into consumer contracts.
#[contracttype(export = false)]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum ActionClass {
    Emergency = 0,
    Standard = 1,
    Critical = 2,
}

/// Who is authorizing an admin action.
pub enum Auth {
    /// The address stored under the contract's admin key must sign.
    Admin,
    /// `(multisig_contract, action_id)`: the multisig must report the
    /// action as executable for the entrypoint's `ActionClass`.
    Multisig(Address, u64),
}

/// Cross-calls `multisig.is_executable(action_id, class)`. Uses
/// `invoke_contract` directly rather than a `contractimport!` client, so
/// no consumer needs multisig's wasm to compile.
pub fn is_executable(env: &Env, multisig: &Address, action_id: u64, class: ActionClass) -> bool {
    env.invoke_contract(
        multisig,
        &Symbol::new(env, "is_executable"),
        vec![env, action_id.into_val(env), class.into_val(env)],
    )
}

/// `Err(unauthorized)` unless `auth` is satisfied: the stored admin's
/// signature for `Auth::Admin`, or an executable multisig approval for
/// `Auth::Multisig`. `Err(not_initialized)` if no admin is stored.
/// Generic over each contract's own storage key and error enum.
pub fn require_admin_or_multisig<K, E>(
    env: &Env,
    admin_key: &K,
    auth: &Auth,
    class: ActionClass,
    unauthorized: E,
    not_initialized: E,
) -> Result<(), E>
where
    K: IntoVal<Env, Val>,
{
    match auth {
        Auth::Admin => get_admin(env, admin_key, not_initialized)?.require_auth(),
        Auth::Multisig(multisig, action_id) => {
            if !is_executable(env, multisig, *action_id, class) {
                return Err(unauthorized);
            }
        }
    }
    Ok(())
}

/// The address stored under `admin_key`, or `Err(not_initialized)`.
pub fn get_admin<K, E>(env: &Env, admin_key: &K, not_initialized: E) -> Result<Address, E>
where
    K: IntoVal<Env, Val>,
{
    env.storage()
        .instance()
        .get(admin_key)
        .ok_or(not_initialized)
}

/// Stores `new_admin` and returns the previous admin, for the caller's
/// own `admin_transferred` event.
pub fn set_admin<K, E>(
    env: &Env,
    admin_key: &K,
    new_admin: &Address,
    not_initialized: E,
) -> Result<Address, E>
where
    K: IntoVal<Env, Val>,
{
    let old = get_admin(env, admin_key, not_initialized)?;
    env.storage().instance().set(admin_key, new_admin);
    Ok(old)
}

pub fn is_paused<K: IntoVal<Env, Val>>(env: &Env, paused_key: &K) -> bool {
    env.storage().instance().get(paused_key).unwrap_or(false)
}

pub fn set_paused<K: IntoVal<Env, Val>>(env: &Env, paused_key: &K, paused: bool) {
    env.storage().instance().set(paused_key, &paused);
}

/// `Err(err)` if the contract is paused.
pub fn require_not_paused<K, E>(env: &Env, paused_key: &K, err: E) -> Result<(), E>
where
    K: IntoVal<Env, Val>,
{
    if is_paused(env, paused_key) {
        return Err(err);
    }
    Ok(())
}
