//! Shared build script for every contract crate (#125). Each contract's
//! manifest sets `build = "../common/build_meta.rs"` and its lib.rs calls
//! `zenith_common::contract_meta!()`, which includes the file written
//! here: one `contractmeta!` entry per key, so every wasm describes itself
//! (`stellar contract info meta --wasm <file>`).
//!
//! | Key | Value |
//! |---|---|
//! | `name` | the crate name, e.g. `zenith-params` |
//! | `binver` | the crate version from Cargo.toml |
//! | `source_repo` | `repository` from Cargo.toml |
//! | `commit` | `ZENITH_GIT_COMMIT` if set (CI sets it to the commit being built), else `git rev-parse HEAD`, else `unknown` |
//!
//! `contractmeta!` only accepts string literals, hence a generated file
//! rather than `env!()` in the source.

use std::{env, fs, path::PathBuf, process::Command};

fn var(name: &str) -> String {
    env::var(name).unwrap_or_default()
}

fn commit() -> String {
    let from_env = var("ZENITH_GIT_COMMIT");
    if !from_env.trim().is_empty() {
        return from_env.trim().to_string();
    }
    Command::new("git")
        .args(["rev-parse", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown".into())
}

/// A Rust string literal for `s`.
fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn main() {
    println!("cargo:rerun-if-changed=../common/build_meta.rs");
    println!("cargo:rerun-if-env-changed=ZENITH_GIT_COMMIT");
    // Re-run when HEAD moves, so a local build's `commit` stays accurate.
    let manifest_dir = PathBuf::from(var("CARGO_MANIFEST_DIR"));
    if let Some(git) = manifest_dir.parent().map(|root| root.join(".git")) {
        let head = git.join("HEAD");
        if head.exists() {
            println!("cargo:rerun-if-changed={}", head.display());
            if let Ok(head) = fs::read_to_string(&head) {
                if let Some(r) = head.strip_prefix("ref: ") {
                    println!("cargo:rerun-if-changed={}", git.join(r.trim()).display());
                }
            }
        }
    }

    let repo = var("CARGO_PKG_REPOSITORY");
    if repo.is_empty() {
        panic!("set `repository` (or `repository.workspace = true`) in this crate's Cargo.toml");
    }
    let entries = [
        ("name", var("CARGO_PKG_NAME")),
        ("binver", var("CARGO_PKG_VERSION")),
        ("source_repo", repo),
        ("commit", commit()),
    ];
    let mut out = String::from("// @generated by common/build_meta.rs\n");
    for (key, val) in entries {
        out.push_str(&format!(
            "soroban_sdk::contractmeta!(key = {}, val = {});\n",
            lit(key),
            lit(&val)
        ));
    }
    let path = PathBuf::from(var("OUT_DIR")).join("contractmeta.rs");
    fs::write(&path, out).unwrap_or_else(|e| panic!("writing {}: {e}", path.display()));
}
